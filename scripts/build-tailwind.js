// Pre-compiles Tailwind CSS ahead of the CRACO/webpack build. See the
// comment in src/tailwind-source.css for why this exists instead of running
// Tailwind inline in webpack's postcss pipeline.
const postcss = require('postcss');
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const inputPath = path.join(projectRoot, 'src/tailwind-source.css');
const outputPath = path.join(projectRoot, 'src/tailwind-generated.css');

async function main() {
  const css = fs.readFileSync(inputPath, 'utf8');

  const result = await postcss([
    require('@tailwindcss/postcss')({ base: projectRoot }),
    require('autoprefixer'),
  ]).process(css, { from: inputPath, to: outputPath });

  fs.writeFileSync(
    outputPath,
    '/* AUTO-GENERATED by scripts/build-tailwind.js — do not edit directly. */\n' + result.css
  );
  console.log(`✅ Tailwind compiled: ${outputPath} (${(result.css.length / 1024).toFixed(1)} KB)`);
}

main().catch(err => {
  console.error('❌ Tailwind pre-build failed:', err);
  process.exit(1);
});
